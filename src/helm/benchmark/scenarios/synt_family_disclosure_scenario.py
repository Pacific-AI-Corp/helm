import sys
import csv
from typing import Dict, List

from helm.benchmark.presentation.taxonomy_info import TaxonomyInfo
from helm.benchmark.scenarios.scenario import (
    Input,
    Scenario,
    Instance,
    TEST_SPLIT,
    CORRECT_TAG,
    Reference,
    Output,
    ScenarioMetadata,
)
from helm.common.general import check_file_exists

csv.field_size_limit(sys.maxsize)


class SyntFamilyDisclosureScenario(Scenario):
    """
    This dataset features synthetic clinical scenarios generated by an LLM and reviewed by
    clinicians. The scenario evaluates the ability of an LLM to determine whether the HIPAA
    Privacy Rule permits a healthcare provider to disclose an adult patient's health information
    to a family member, friend, or other person involved in the patient's care.
    """

    name = "synt_family_disclosure"
    description = (
        "FamilyDisclosure is a benchmark of synthetic clinical scenarios that tests whether"
        " a model can determine when the HIPAA Privacy Rule permits a healthcare provider to "
        "disclose an adult patient's health information to a family member, friend, or other "
        "person involved in the patient's care."
    )
    tags = ["knowledge", "reasoning", "biomedical"]

    POSSIBLE_ANSWER_CHOICES: List[str] = ["A", "B"]

    def __init__(self, data_path: str):
        super().__init__()
        self.data_path = data_path

    def create_benchmark(self, csv_path) -> Dict[str, str]:
        data = {}
        with open(csv_path, "r") as file:
            reader = csv.DictReader(file)
            for row in reader:
                question = row["prompt"]
                context = row["context"]
                answer = row["label"]
                prompt = (
                    "You are reviewing a clinical scenario to determine whether a healthcare provider is "
                    "permitted under the HIPAA Privacy Rule to disclose an adult patient's health information "
                    "to a family member, friend, or other person involved in the patient's care. "
                    f"Please answer the following question: {question} using the following context: {context}. "
                    "Answer 'A' if the disclosure is permitted and 'B' if the disclosure is not permitted. "
                    "Do not provide any additional details or explanation; respond with only A or B."
                )
                data[prompt] = answer
        return data

    def get_instances(self, output_path: str) -> List[Instance]:
        check_file_exists(
            self.data_path, msg=f"[SyntFamilyDisclosureScenario] Required data file not found: '{self.data_path}'"
        )
        instances: List[Instance] = []
        benchmark_data = self.create_benchmark(self.data_path)

        for prompt, answer in benchmark_data.items():
            assert answer in SyntFamilyDisclosureScenario.POSSIBLE_ANSWER_CHOICES
            references: List[Reference] = [
                Reference(Output(text=pred_answer), tags=[CORRECT_TAG] if pred_answer == answer else [])
                for pred_answer in SyntFamilyDisclosureScenario.POSSIBLE_ANSWER_CHOICES
            ]
            instances.append(
                Instance(
                    input=Input(text=prompt),
                    references=references,  # [Reference(Output(text=answer), tags=[CORRECT_TAG])],
                    split=TEST_SPLIT,
                )
            )

        return instances

    def get_metadata(self):
        return ScenarioMetadata(
            name="synt_family_disclosure",
            display_name="FamilyDisclosure",
            description=(
                "Predict whether a healthcare provider is permitted under the HIPAA Privacy Rule "
                "to disclose an adult patient's health information to a family member, friend, "
                "or other person involved in the patient's care."
            ),
            taxonomy=TaxonomyInfo(
                task="Classification",
                what="Classify whether disclosure of an adult patient's health information is permitted",
                when="Any",
                who="Clinician, Caregiver, Family Member, Friend",
                language="English",
            ),
            main_metric="exact_match",
            main_split="test",
        )
