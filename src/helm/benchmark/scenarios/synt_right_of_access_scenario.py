import sys
import csv
from typing import Dict, List

from helm.benchmark.presentation.taxonomy_info import TaxonomyInfo
from helm.benchmark.scenarios.scenario import (
    Input,
    Scenario,
    Instance,
    TEST_SPLIT,
    CORRECT_TAG,
    Reference,
    Output,
    ScenarioMetadata,
)
from helm.common.general import check_file_exists

csv.field_size_limit(sys.maxsize)


class SyntRightOfAccessScenario(Scenario):
    """
    This dataset features synthetic, PHI-free clinical scenarios generated by an LLM and
    reviewed by clinicians. The scenario evaluates an LLM's ability to determine how the
    HIPAA Right of Access under 45 CFR 164.524 applies when an individual or their personal
    representative requests access to their own health information.
    """

    name = "synt_right_of_access"
    description = (
        "RightOfAccess is a benchmark of synthetic clinical scenarios that tests whether a model "
        "can determine how the HIPAA Right of Access under 45 CFR 164.524 applies to requests for "
        "an individual's own health information."
    )
    tags = ["knowledge", "reasoning", "biomedical"]

    POSSIBLE_ANSWER_CHOICES: List[str] = ["A", "B", "C"]

    def __init__(self, data_path: str):
        super().__init__()
        self.data_path = data_path

    def create_benchmark(self, csv_path) -> Dict[str, str]:
        data = {}
        with open(csv_path, "r") as file:
            reader = csv.DictReader(file)
            for row in reader:
                question = row["prompt"]
                context = row["context"]
                answer = row["label"]
                prompt = (
                    "You are reviewing a clinical scenario involving a request for access to an individual's "
                    "own health information under the HIPAA Right of Access (45 CFR 164.524). "
                    f"Please answer the following question: {question} using the following context: {context}. "
                    "Answer 'A' if access must be granted, 'B' if access may be denied without review, or "
                    "'C' if access may be denied on a reviewable ground. "
                    "Respond with only A, B, or C and no additional explanation."
                )
                data[prompt] = answer
        return data

    def get_instances(self, output_path: str) -> List[Instance]:
        check_file_exists(
            self.data_path, msg=f"[SyntRightOfAccessScenario] Required data file not found: '{self.data_path}'"
        )
        instances: List[Instance] = []
        benchmark_data = self.create_benchmark(self.data_path)

        for prompt, answer in benchmark_data.items():
            assert answer in SyntRightOfAccessScenario.POSSIBLE_ANSWER_CHOICES
            references: List[Reference] = [
                Reference(Output(text=pred_answer), tags=[CORRECT_TAG] if pred_answer == answer else [])
                for pred_answer in SyntRightOfAccessScenario.POSSIBLE_ANSWER_CHOICES
            ]
            instances.append(
                Instance(
                    input=Input(text=prompt),
                    references=references,  # [Reference(Output(text=answer), tags=[CORRECT_TAG])],
                    split=TEST_SPLIT,
                )
            )

        return instances

    def get_metadata(self):
        return ScenarioMetadata(
            name="synt_right_of_access",
            display_name="RightOfAccess",
            description=(
                "Predict how the HIPAA Right of Access under 45 CFR 164.524 applies when an "
                "individual or their personal representative requests access to their own health information."
            ),
            taxonomy=TaxonomyInfo(
                task="Classification",
                what="Classify whether access must be granted or may be denied under the HIPAA Right of Access",
                when="Any",
                who="Individual, Personal Representative, Covered Entity",
                language="English",
            ),
            main_metric="exact_match",
            main_split="test",
        )
